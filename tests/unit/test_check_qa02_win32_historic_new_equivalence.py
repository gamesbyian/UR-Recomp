"""Synthetic unit contract for exact old P0 vs new journal Win32 evidence.

These are generated byte arrays, not genuine Windows process witnesses.
"""
from __future__ import annotations

import hashlib
import json
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tests" / "unit"))
from check_qa02_win32_historic_new_equivalence import compare  # noqa: E402
from test_check_qa02_win32_fault_snapshots import (  # noqa: E402
    EXE, SOURCE, make_members, pack
)
from test_check_qa02_win32_original_fault_envelope import (  # noqa: E402
    original_members, write_zip
)


class HistoricVsRecoveredWin32Test(unittest.TestCase):
    def originals(self, root: Path):
        old, old_sha = pack(root, make_members("historic"))
        new, new_sha = write_zip(root, original_members())
        return old, old_sha, new, new_sha

    def test_exact_same_source_raw_negative_and_positive_journal(self):
        with tempfile.TemporaryDirectory() as d:
            old, old_sha, new, new_sha = self.originals(Path(d))
            receipt = compare(old, old_sha, SOURCE, EXE, new, new_sha)
            self.assertEqual(
                receipt["independently_identical_old_negative_new_unjournaled_files"], 8)
            self.assertTrue(receipt["new_journaled_raw_crash_identical_to_original"])
            self.assertEqual(receipt["raw_changed_byte_count"], 1)
            self.assertEqual(receipt["release_gate_credit"], 0)

    def test_mismatching_original_selector_rejected_despite_valid_own_receipt(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            old_members = make_members("historic")
            changed = b"valid-but-different-historic-selector"
            old_members["selector.before.bin"] = changed
            old_members["selector.after.bin"] = changed
            receipts = json.loads(old_members["file-receipt.json"].decode())
            for stage in ("before", "after"):
                receipts["selector"][stage + "_sha256"] = hashlib.sha256(changed).hexdigest()
                receipts["selector"][stage + "_bytes"] = len(changed)
            old_members["file-receipt.json"] = json.dumps(receipts).encode()
            old, old_sha = pack(root, old_members)
            new, new_sha = write_zip(root, original_members())
            with self.assertRaisesRegex(ValueError, "old negative vs new unjournaled"):
                compare(old, old_sha, SOURCE, EXE, new, new_sha)

    def test_different_external_original_zip_digests_rejected(self):
        with tempfile.TemporaryDirectory() as d:
            old, old_sha, new, new_sha = self.originals(Path(d))
            with self.assertRaises(ValueError):
                compare(old, "0" * 64, SOURCE, EXE, new, new_sha)
            with self.assertRaises(ValueError):
                compare(old, old_sha, SOURCE, EXE, new, "0" * 64)

    def test_cross_source_fabricated_new_guest_delta_rejected(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            old, old_sha = pack(root, make_members("historic"))
            members = original_members()
            target = "native_intent_restart_recovery/fault-bytes/raw-sram.after.bin"
            members[target] = b"?" + members[target][1:]
            new, new_sha = write_zip(root, members)
            with self.assertRaises(ValueError):
                compare(old, old_sha, SOURCE, EXE, new, new_sha)


if __name__ == "__main__":
    unittest.main()
