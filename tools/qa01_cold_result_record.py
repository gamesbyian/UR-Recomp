ROM_SHA = "859ec99fdc25dd9b239d9085bf656e4f49c93a32faa5bb248da83efd68ebd478"
MOVIE_SHA = "06dce29e9d36997fc2a1fac4bab72180ab6c8096366cfcf05780c1b2dea4b442"
INPUT_SHA = "04ad1c2d70b38d3f33513468be2c94acc4b0c452a323631aebb390a3542f75e8"
# Exact script generated by the existing opt-in authentic Zoo-to-Bowl replay.
# The script is source-identical in controller masks to the archived movie,
# but its longer dump schedule changes its SHA-256. Do not accept arbitrary
# new hashes as a substitute for original-source provenance.
NEXT_BOWL_INPUT_SHA = "414cb0b1013509f60faf35102353dd10ce36fc684284dd46af11092ad22c5de9"
# Independently SHA-verified expanded source controller script of the *same*
# 2014 USA Zoo movie, used by exact composite ELF run 38884542449. It adds
# read-only race-mesh/DP dumps; not a different controller policy or ROM.
COMPOSITE_MESH_NEXT_BOWL_INPUT_SHA = "1eb3e8416b7fa40935d097c78d281ca98537c9a555e23f1906a99912dcdb2c52"
NEXT_BOWL_MOVIE_WINDOW_SHA = "7b03f40e3401d844c16c7c4e1cc7375e5419f33882793c8187dcebc88dbc8c93"
SIZE = 8192
BOOT_FRAMES = (300, 420)


class ColdProofError(ValueError):
    pass


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def byte_image(path: Path, sha256: str) -> bytes:
    if not path.is_file():
        raise ColdProofError(f"missing SRAM image {path}")
    data = path.read_bytes()
    if len(data) != SIZE or digest(data) != sha256:
        raise ColdProofError(f"SRAM image wrong size or SHA256 {path}")
    return data


def ranked(data: bytes) -> dict:
    if len(data) != SIZE:
        raise ColdProofError("cold record image must be 8KiB")
    word = lambda at: int.from_bytes(data[at:at + 2], "little")
    record_table = data[0x0422:0x054E]
    holders = data[0x0550:0x05E6]
    return {
        "crawler_zoo_rank0_value": word(0x0422 + 2),
        "crawler_zoo_rank0_holder": data[0x0550 + 1],
        "record_checksum_stored": word(0x054E),
        "record_checksum_calculated": sum(
            word(0x0422 + 2 * k) for k in range(150)) & 0xFFFF,
        "all_150_record_words_sha256": digest(record_table),
        "all_150_record_holders_sha256": digest(holders),
    }


def validate_source(producer: dict, replay: Path) -> dict:
    if (producer.get("schema_version") != 1
            or producer.get("name") != "zoom-zoo"
            or producer.get("course_id") != "course:02"
            or producer.get("native_backend") != "pinned-baldosa"
            or producer.get("rom_sha256") != ROM_SHA
            or producer.get("original_movie_sha256") != MOVIE_SHA
            or producer.get("original_source_event", {}).get("original_entry_frame") != 3190
            or producer.get("original_source_event", {}).get("original_result_frame") != 8353):
        raise ColdProofError("not source-pinned original 2014 Zoom Zoo event")
    input_sha = producer.get("input_sha256")
    if input_sha in (NEXT_BOWL_INPUT_SHA, COMPOSITE_MESH_NEXT_BOWL_INPUT_SHA):
        handoff = producer.get("zoo_next_bowl_handoff")
        if (producer.get("reference_script_sha256") != NEXT_BOWL_INPUT_SHA
                or producer.get("original_movie_window_sha256") !=
                NEXT_BOWL_MOVIE_WINDOW_SHA
                or not isinstance(handoff, dict)
                or handoff.get("source_next_bowl_active_entry_offset") != 267
                or handoff.get("fresh_reference_next_bowl_entry_offset") != 267
                or handoff.get("fresh_native_next_bowl_entry_offset") != 267
                or handoff.get("next_bowl_entry_triple_equal") is not True
                or handoff.get("all_original_native_full_sram_pairs_equal") is not True
                or handoff.get("release_complete_event_credit") != 0):
            raise ColdProofError("extended Zoo source movie/window/handoff not pinned")
        if input_sha == COMPOSITE_MESH_NEXT_BOWL_INPUT_SHA:
            # A source-correct expanded replay cannot be authenticated by
            # swapping a digest alone: require its actual unmasked original/
            # native mesh and the full consecutive SPC direct-page window.
            mesh = producer.get("zoo_race_mesh")
            expected = original.sample_frames("zoom-zoo", 5163,
                                              zoo_race_mesh=True,
                                              zoo_dp_window=True)
            if (not isinstance(mesh, dict)
                    or mesh.get("schema") != "UR-QA01-ZOO-FULL-RACE-UNMASKED-WRAM-MESH/1"
                    or mesh.get("archived_source_active_frames_to_result") != 5163
                    or type(producer.get("reference_entry")) is not int
                    or type(producer.get("native_entry")) is not int
                    or mesh.get("original_2014_source_controller_masks_modified") is not False
                    or mesh.get("masked_or_excluded_wram_bytes") != 0
                    or mesh.get("all_128k_wram_bytes_examined_per_pair") != 131072
                    or mesh.get("mesh_checkpoint_count") != len(expected)
                    or mesh.get("last_race_relative_checkpoint") != expected[-1]
                    or mesh.get("every_gameplay_frame_compared") is not False
                    or mesh.get("release_complete_usa_event_credit") != 0
                    or not isinstance(mesh.get("samples"), list)
                    or len(mesh["samples"]) != len(expected)):
                raise ColdProofError("composite Zoo source mesh missing or over-promotional")
            for offset, row in zip(expected, mesh["samples"]):
                pair = row.get("original_native_full_wram_byte_difference", {}) if isinstance(row, dict) else {}
                if (not isinstance(row, dict)
                        or row.get("race_relative_frame") != offset
                        or row.get("original_absolute_host_frame") != producer.get("reference_entry", -1) + offset
                        or row.get("native_absolute_host_frame") != producer.get("native_entry", -1) + offset
                        or pair.get("every_byte_compared") is not True
                        or pair.get("full_wram_bytes_per_guest") != 131072
                        or pair.get("excluded_byte_count") != 0
                        or type(pair.get("differing_byte_count")) is not int
                        or not 0 <= pair["differing_byte_count"] <= 131072):
                    raise ColdProofError("composite Zoo unmasked mesh frame absent or unanchored")
            dp = mesh.get("late_direct_page_window")
            if (not isinstance(dp, dict)
                    or dp.get("schema") != "UR-QA01-ZOO-5040-DENSE-DP-WRAM/1"
                    or dp.get("range_inclusive") != [5034, 5046]
                    or dp.get("all_guest_frames_in_range_captured") is not True
                    or dp.get("raw_wram_bytes_excluded") != 0
                    or dp.get("release_complete_event_credit") != 0
                    or not isinstance(dp.get("samples"), list)
                    or [row.get("race_relative_frame") for row in dp["samples"]
                        if isinstance(row, dict)] != list(range(5034, 5047))):
                raise ColdProofError("composite Zoo original/native 13-frame SPC window missing")
    elif input_sha != INPUT_SHA:
        raise ColdProofError("unknown original Zoo controller replay script SHA256")
    cmp = producer.get("comparison")
    if (not isinstance(cmp, dict)
            or cmp.get("terminal_result_guest_frame") != {
                "reference_relative": 5163, "native_relative": 5163}
            or cmp.get("terminal_result_frame_matched") is not True
            or cmp.get("rendered_result_and_score_text_matched") is not True
            or cmp.get("circuit_multiple_lap_decrements_sampled") is not True):
        raise ColdProofError("missing true corrected original/native completed Circuit")
    follow = producer.get("source_terminal_followthrough")
    if (not isinstance(follow, dict)
            or follow.get("schema") !=
            "UR-QA01-SOURCE-ORIGINAL-NATIVE-RESULT-FOLLOWTHROUGH/2"
            or follow.get("sample_count") != 6
            or follow.get("release_complete_usa_event_credit") != 0
            or follow.get("battery_sram_cold_process_persistence_proven") is not False):
        raise ColdProofError("invalid opt-in followthrough or premature credit")
    samples = follow.get("samples")
    if (not isinstance(samples, list)
            or [s.get("offset_from_each_observed_result_onset") for s in samples
                if isinstance(s, dict)] != [8, 16, 24, 32, 64, 72]):
        raise ColdProofError("incomplete or reordered original/native followthrough")
    seeds = {}
    for side, dirname in (("original", "ref"), ("native", "native")):
        entry = samples[-1].get("fresh_guest_battery_sram", {}).get(side)
        if (not isinstance(entry, dict)
                or entry.get("full_sram_bytes") != SIZE
                or entry.get("crawler_course_track_index") != 1
                or entry.get("in_memory_snapshot_only") is not True
                or entry.get("cold_process_reload_proven") is not False):
            raise ColdProofError("not a genuine bounded recorded battery snapshot")
        path = replay / dirname / "original-follow-72.sram.bin"
        seed = byte_image(path, entry.get("sram_sha256", ""))
        d = ranked(seed)
        if (d["crawler_zoo_rank0_value"] != 2510
                or d["crawler_zoo_rank0_holder"] != 0
                or d["record_checksum_stored"] != d["record_checksum_calculated"]
                or d["record_checksum_stored"] != entry.get("record_table_checksum_stored")
                or entry.get("crawler_record_three_ranks", [None])[0] != {
                    "rank": 0, "value_word": 2510, "holder_index": 0}):
            raise ColdProofError("seed lacks independently earned MIKE 25.10 best lap")
        seeds[side] = {"path": path, "sha256": digest(seed), "records": d}
    return seeds


def evaluate_cold(seeds: dict, root: Path) -> dict:
    rows = []
    for f in BOOT_FRAMES:
        out = {}
        for side, path in (
                ("original", root / "original" / "ref" / f"cold-{f:03d}.sram.bin"),
                ("native", root / "native" / "native" / f"cold-{f:03d}.sram.bin")):
            if not path.is_file() or path.stat().st_size != SIZE:
                raise ColdProofError(f"missing fresh-process cold SRAM {path}")
            raw = path.read_bytes()
            d = ranked(raw)
            if d != seeds[side]["records"]:
                raise ColdProofError(
                    f"{side} lost or rewrote original ranked-record bytes on cold start +{f}")
            out[side] = {"post_boot_sram_sha256": digest(raw),
                         "record_layout": d}
        if out["original"]["record_layout"] != out["native"]["record_layout"]:
            raise ColdProofError("fresh original/native ranked records disagree")
        rows.append({"boot_host_frame": f, "fresh_guests": out})
    return {
        "schema": "UR-QA01-ZOO-COLD-GUEST-RECORD-RELOAD/1",
        "source_seed_sha256": {side: seeds[side]["sha256"] for side in seeds},
        "source_qualified_best_lap_centiseconds": 2510,
        "two_independent_new_guest_processes_observed": True,
        "fresh_guest_loaded_ranked_records_and_checksum": True,
        "boot_observations": rows,
        "input_images_are_producer_sram_dumps_not_disk_autosave_files": True,
        "native_host_disk_publish_or_hard_kill_proven": False,
        "source_original_full_event_fidelity_proven": False,
        "strict_full_frame_parity_proven": False,
        "cold_process_record_load_only": True,
        "release_complete_usa_event_credit": 0,
    }


def execute(args) -> dict:
    producer = json.loads(args.producer_report.read_text(encoding="utf-8"))
    if (digest(args.rom.read_bytes()) != producer.get("rom_sha256")
            or digest(args.core.read_bytes()) != producer.get("reference_core_sha256")
            or digest(args.native.read_bytes()) != producer.get("native_executable_sha256")):
        raise ColdProofError("cold replay binary or ROM differs from source-qualified producer")
    seeds = validate_source(producer, args.replay)
    if args.work.exists():
        raise ColdProofError("cold reload requires an unused output root")
    args.work.mkdir(parents=True)
    script = args.work / "cold.script"
    script.write_text("wait 300\ndump cold-300\nwait 120\ndump cold-420\nquit\n",
                      encoding="ascii")
    for side in ("original", "native"):
        work = args.work / side
        work.mkdir()
        cfg = SimpleNamespace(**vars(args))
        cfg.sram = seeds[side]["path"]
        if side == "original":
            log = runner.run_reference(work, cfg, script, [])
        else:
            log = original.run_pinned_baldosa(work, cfg, script, [], 0)
        (args.work / f"{side}.log").write_text(log, encoding="utf-8")
        for frame in BOOT_FRAMES:
            if original.observed_dump_frame(log, f"cold-{frame:03d}") != frame:
                raise ColdProofError(f"unanchored fresh {side} boot frame")
    result = evaluate_cold(seeds, args.work)
    result["source_identity"] = {
        k: producer[k] for k in ("rom_sha256", "original_movie_sha256",
                                "input_sha256", "reference_core_sha256",
                                "native_executable_sha256",
                                "original_movie_window_sha256")}
    result["source_producer_report_sha256"] = digest(args.producer_report.read_bytes())
    return result


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    for name in ("producer-report", "replay", "snesref", "core", "native",
                 "rom", "work", "out"):
        p.add_argument("--" + name, required=True, type=Path)
    a = p.parse_args()
    for key in ("producer_report", "replay", "snesref", "core", "native", "rom", "work", "out"):
        setattr(a, key, getattr(a, key).resolve())
    result = execute(a)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n",
                     encoding="utf-8")
    print("Genuine Zoom Zoo 25.10 cold guest ranked-record load observed; 0/45 event credit")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
