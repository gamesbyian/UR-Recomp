"""Make the release-event census generated limits source-consistent.

The generator remains authoritative; positive CI proves generated bytes
match the real catalog and evidence, rather than just two copied strings.
"""
from pathlib import Path
import subprocess
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]


class CourseEventCensusSourceSyncTests(unittest.TestCase):
    def test_generated_census_matches_authoritative_sources(self):
        result = subprocess.run(
            [sys.executable, "tools/audit_original_course_event_coverage.py", "--check"],
            cwd=ROOT, capture_output=True, text=True, timeout=30)
        self.assertEqual(result.returncode, 0, result.stderr + result.stdout)


if __name__ == "__main__":
    unittest.main()
