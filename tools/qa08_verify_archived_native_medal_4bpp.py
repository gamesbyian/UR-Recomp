#!/usr/bin/env python3
"""Replay exact Windows RF017 medal OAM/4bpp provenance from retained source.

Read only the SHA-256-pinned original Windows Actions raw log, not a guessed
SNES sprite, separate software PPU, adjusted video, or rendered image.
The recorded Windows run had already checked the 5484 guest route CRC
before its postprocessor rejected CGRAM colour in place of OBJ zbuffer.
That guest CRC is NOT independently regenerated by this log-only replay.
"""
from __future__ import annotations
import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import zipfile

ARCHIVE_SHA="725ef03df3d43ff5d30b4bea944e32555974fb0b0e01af025da76ef88959b408"
LOG_SHA="ff0ca813911fb4b8d3c61cadc358df49e8b409e82eae9619956a09ce3433a602"
RUN_ID=39123459879
ARTIFACT_ID=12134793278
HEAD_SHA="59063914449e34f1513631217e3099152e8e4b07"
FRAMES=(4032,4048,4064,4080,4176)
POINTS=((207,91),(205,115),(205,139),(225,96),(225,120))
FETCH="UR_QA08_WIN_OBJ_FETCH "
OWNER="UR_QA08_WIN_PIXEL_OWNER "
OAM="UR_QA08_WIN_OAM_LINE "
CGRAM="UR_QA08_WIN_CURRENT_CGRAM_WRITE "
COUNTS={FETCH:25,OWNER:25,OAM:175,CGRAM:276}
FETCH_FIELDS=set(("frame","x","raster_y","slot","oam","attrs","oam_tile",
                   "used_tile","objadr","row","src_col","px","palette",
                   "priority","pixel","plane","writer_obj"))
OWNER_REQUIRED={"frame","x","raster_y","ppu_line","main","sub","obj","obj_word",
                "obj_cgram_index","inidisp","cgadsub","final"}

def sha(raw:bytes)->str:
    return hashlib.sha256(raw).hexdigest()

def fields(line:str,tag:str)->dict[str,str]:
    if not line.startswith(tag):
        raise ValueError("foreign native source line")
    result={}
    for pair in line[len(tag):].split():
        if pair.count("=")!=1:
            raise ValueError("malformed native pixel source operand")
        k,v=pair.split("=",1)
        if k in result:
            raise ValueError("duplicate source operand")
        result[k]=v
    return result

def checked_fetch(row:dict[str,str])->dict:
    if set(row)!=FETCH_FIELDS:
        raise ValueError("physical 4bpp fetch fields missing or changed")
    decimal=("frame","x","raster_y","slot","row","src_col","px","priority")
    try:
        x={k:int(v,10 if k in decimal else 16) for k,v in row.items()}
    except ValueError as exc:
        raise ValueError("source OAM/VRAM operand not numeric") from exc
    if (x["frame"] not in FRAMES or (x["x"],x["raster_y"]) not in POINTS or
        x["slot"] not in range(128) or
        not (0<=x["attrs"]<=65535 and 0<=x["oam"]<=65535) or
        x["attrs"]&0xff!=x["oam_tile"] or
        not 0<=x["used_tile"]<1024 or
        not 0<=x["objadr"]<32768 or
        not 0<=x["row"]<64 or not 0<=x["src_col"]<64 or
        not 0<=x["px"]<8 or
        x["palette"] not in range(0x80,0x100,16) or
        not 0<=x["priority"]<=255 or
        not 1<=x["pixel"]<=15 or
        not 0<=x["plane"]<2**32):
        raise ValueError("physical source tile or coordinate unsupported")
    shift=x["px"] if x["attrs"]&0x4000 else 7-x["px"]
    bits=x["plane"] >> shift
    four=(bits&1)|((bits>>7)&2)|((bits>>14)&4)|((bits>>21)&8)
    encoded=(x["priority"]<<8)+x["palette"]+x["pixel"]
    if four!=x["pixel"] or encoded!=x["writer_obj"]:
        raise ValueError("source 4bpp bitplanes or encoded OBJ priority fail")
    return x

def replay(raw:bytes)->dict:
    if sha(raw)!=LOG_SHA:
        raise ValueError("authentic current Win32 source log SHA changed")
    text=raw.decode("utf-8")
    collected={tag:[] for tag in COUNTS}
    for line in text.splitlines():
        for tag in COUNTS:
            if line.startswith(tag):
                collected[tag].append(fields(line,tag))
                break
    if any(len(collected[tag])!=count for tag,count in COUNTS.items()):
        raise ValueError("missing, duplicate or truncated original native source records")
    owners={}
    for row in collected[OWNER]:
        if not OWNER_REQUIRED.issubset(row):
            raise ValueError("unqualified effective PPU pixel owner")
        key=(int(row["frame"]),int(row["x"]),int(row["raster_y"]))
        if key in owners or key[0] not in FRAMES or key[1:] not in POINTS or (
            int(row["ppu_line"])!=key[2]+1):
            raise ValueError("effective compositor raster/source registration mismatch")
        owners[key]=row
    expected={(frame,x,y) for frame in FRAMES for x,y in POINTS}
    if set(owners)!=expected:
        raise ValueError("missing or unexpected owner-source coordinate")
    candidate=defaultdict(list)
    for row in collected[FETCH]:
        x=checked_fetch(row)
        candidate[x["frame"],x["x"],x["raster_y"]].append(x)
    if not set(candidate).issubset(expected):
        raise ValueError("source sprite fetch not registered to tested raster")
    wins=[]
    bg_controls=[]
    for frame,x,y in sorted(expected):
        effective=owners[frame,x,y]
        writes=candidate.get((frame,x,y),[])
        if effective["main"]=="4":
            if not writes:
                raise ValueError("OBJ main pixel has no genuine source fetch")
            last=writes[-1]
            z=int(effective["obj"],16)   # encoded hardware OBJ buffer word
            colour=int(effective["obj_word"],16) # CGRAM RGB15, NOT zbuffer
            if z!=last["writer_obj"]:
                raise ValueError("actual 4bpp final OBJ does not match real compositor")
            wins.append({
                "guest":frame,"xy":[x,y],
                "source_winning_OAM_slot":last["slot"],
                "source_winning_tile_name":f"{last['oam_tile']:02x}",
                "source_used_4bpp_tile_index":last["used_tile"],
                "source_tile_vram_word_base":last["objadr"],
                "source_4bpp_plane":f"{last['plane']:08x}",
                "source_pixel_nibble":last["pixel"],
                "source_CGRAM_palette_base":f"{last['palette']:02x}",
                "source_encoded_sprite_priority":last["priority"],
                "source_last_obj_zbuffer_word":f"{z:04x}",
                "separate_CGRAM_colour_RGB15":f"{colour:04x}",
                "physical_OAM_writers_this_pixel":len(writes),
                "all_source_writers_preserved":True
            })
        elif effective["main"]=="0":
            if writes:
                raise ValueError("BG1-main negative control unexpectedly has sprite writes")
            bg_controls.append({"guest":frame,"xy":[x,y],"main_layer":"BG1"})
        else:
            raise ValueError("not an adjudicated BG1/OBJ medal pixel")
    overlaps=sum(1 for w in wins if w["physical_OAM_writers_this_pixel"]>1)
    if len(wins)!=19 or len(bg_controls)!=6 or overlaps!=6 or len(candidate)!=19:
        raise ValueError("source exact native OBJ/BG1 count changed")
    return {
        "schema":"qa08-original-native-medal-real-4bpp-physical-source-archive/1",
        "run_id":RUN_ID,"artifact_id":ARTIFACT_ID,"source_pr_head":HEAD_SHA,
        "actual_raw_source_sha256":LOG_SHA,"actual_archive_sha256":ARCHIVE_SHA,
        "actual_physical_4bpp_fetches":len(collected[FETCH]),
        "actual_effective_PPU_owner_pixels":len(collected[OWNER]),
        "actual_OAM_line_records":len(collected[OAM]),
        "actual_CGRAM_port_records":len(collected[CGRAM]),
        "source_registered_native_OBJ_winner_count":len(wins),
        "source_native_BG1_negative_controls":len(bg_controls),
        "source_double_write_coordinates":overlaps,
        "source_native_obj_winners":wins,
        "source_native_BG1_controls":bg_controls,
        "strict_5484_frame_CRC_recomputed_from_this_log":False,
        "original_2014_Snes9x_effective_pixel_owner_identical_proven":False,
        "original_vs_native_PPU_2014_tile_parity_accepted":False,
        "global_video_shift_or_tile_reindex_authorized":False,
        "cpu_nmi_phase_root_cause_proven":False,
        "renderer_or_release_approved":False
    }

def verify_archive(path:Path)->dict:
    blob=path.read_bytes()
    if sha(blob)!=ARCHIVE_SHA:
        raise ValueError("archived real Windows artifact outer SHA mismatch")
    with zipfile.ZipFile(path) as z:
        if z.namelist()!=["baseline/log.txt"] or z.getinfo("baseline/log.txt").is_dir():
            raise ValueError("original Windows source artifact inventory changed")
        return replay(z.read("baseline/log.txt"))

def main()->None:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--archive",type=Path,required=True)
    p.add_argument("--out",type=Path,required=True)
    a=p.parse_args()
    r=verify_archive(a.archive)
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(json.dumps(r,indent=2,sort_keys=True)+"\n",encoding="utf8")
    print("QA08_ORIGINAL_MEDAL_4BPP",r["source_registered_native_OBJ_winner_count"],
          "native_obj_winners BG1_controls",r["source_native_BG1_negative_controls"],
          "original_Snes9x_parity=0 release=0")
if __name__=="__main__":main()
